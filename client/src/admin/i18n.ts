const dictionaries = { ro, en };

/** The site's i18n (dates, numbers, the language switch), with `t` for the admin's words and `tb` for the site's. */
export function useAdminI18n() {
  const i18n = useI18n();
  return useMemo(() => {
    const dictionary = dictionaries[i18n.lang];
    const t = (key: AdminKey, vars?: Record<string, string | number>) =>
      (dictionary[key] ?? ro[key] ?? key).replace(/\{(\w+)\}/g, (match, name: string) => String(vars?.[name] ?? match));
    return { ...i18n, t, tb: i18n.t };
  }, [i18n]);
}
